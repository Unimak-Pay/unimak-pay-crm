#!/usr/bin/env node
// Generates the typed API layer from openapi.yaml (the contract; never edit the outputs):
//   src/api/schema.gen.ts       openapi-typescript paths/components
//   src/api/permissions.gen.ts  operationId → { method, path, permission } from `x-permission`
//
//   pnpm gen:api           write the files
//   pnpm gen:api --check   fail if they are out of date (CI)
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { parse } from "yaml";

const root = new URL("../", import.meta.url);
const specUrl = new URL("openapi.yaml", root);
const check = process.argv.includes("--check");
const banner = "// GENERATED by scripts/gen-api.mjs from openapi.yaml. Do not edit; run `pnpm gen:api`.\n";

const spec = parse(await readFile(specUrl, "utf8"));

// ── types ──
const ast = await openapiTS(specUrl, { alphabetize: false, defaultNonNullable: false, enumValues: true });
const schemaTs = banner + dedupeEnumValues(astToString(ast));

/**
 * enumValues can emit the same const name twice (e.g. `payerKindValues` for the inline enum
 * `Payer.kind` and for the `PayerKind` schema). The top-level schema keeps the name; inline
 * ones get their parent schema as a prefix (`payerKindValues` → `payer_kindValues`).
 */
function dedupeEnumValues(src) {
  const re = /^export const (\w+Values): ReadonlyArray<FlattenedDeepRequired<\w+>((?:\["[^"]+"\])+)>/gm;
  const decls = [...src.matchAll(re)].map((m) => ({ name: m[1], path: [...m[2].matchAll(/\["([^"]+)"\]/g)].map((x) => x[1]), text: m[0] }));
  const byName = Object.groupBy(decls, (d) => d.name);
  let out = src;
  for (const [name, group] of Object.entries(byName)) {
    if (group.length < 2) continue;
    for (const d of group) {
      const topLevel = d.path.length === 2 && d.path[0] === "schemas";
      if (topLevel) continue;
      const parent = d.path[d.path.length - 2];
      const renamed = `${parent.charAt(0).toLowerCase()}${parent.slice(1)}_${name}`;
      out = out.replace(d.text, d.text.replace(`export const ${name}:`, `export const ${renamed}:`));
    }
  }
  return out;
}

// ── permissions ──
const METHODS = ["get", "post", "put", "patch", "delete"];
const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  if (!path.startsWith("/v1/admin/")) continue;
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    if (!op.operationId) throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
    ops.push({ operationId: op.operationId, method, path, permission: op["x-permission"] ?? null });
  }
}
ops.sort((a, b) => a.operationId.localeCompare(b.operationId));
const permissionsTs =
  banner +
  'import type { components } from "./schema.gen";\n\n' +
  'export type Permission = components["schemas"]["Permission"];\n\n' +
  "/** Every admin operation and the permission it needs (`null`: any signed-in admin). */\n" +
  "export const OPERATIONS = {\n" +
  ops
    .map(
      (o) =>
        `  ${o.operationId}: { method: "${o.method}", path: "${o.path}", permission: ${
          o.permission ? `"${o.permission}"` : "null"
        } },`,
    )
    .join("\n") +
  "\n} as const satisfies Record<string, { method: string; path: string; permission: Permission | null }>;\n\n" +
  "export type OperationId = keyof typeof OPERATIONS;\n";

const outputs = [
  ["src/api/schema.gen.ts", schemaTs],
  ["src/api/permissions.gen.ts", permissionsTs],
];

let stale = false;
for (const [rel, content] of outputs) {
  const file = fileURLToPath(new URL(rel, root));
  if (check) {
    const current = await readFile(file, "utf8").catch(() => "");
    if (current !== content) {
      console.error(`✗ ${rel} is out of date. Run \`pnpm gen:api\`.`);
      stale = true;
    }
  } else {
    await writeFile(file, content);
    console.log(`✓ ${rel}`);
  }
}
if (stale) process.exit(1);
if (!check) console.log(`  ${ops.length} admin operations`);
